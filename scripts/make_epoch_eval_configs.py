#!/usr/bin/env python3
"""
Write the evaluation-only configs that score a multi-epoch cell's checkpoints.

Evaluation runs once, after training, so a three-epoch cell yields one held-out
number and the epochs cannot be told apart. `save_epoch_checkpoints` keeps the
weights at each boundary; this script writes one config per earlier checkpoint,
which re-runs evaluation alone against the cell's own held-out split.

The final epoch needs no config: its checkpoint holds the same weights as the
run's own model, which the cell already evaluated. The script verifies that
rather than assuming it, and refuses a cell where it does not hold.

Configs land under config/epoch_eval/<cell>_ep<N>/, outside
config/ablation_config/ so the orchestrator's folder discovery is unaffected.
Each writes its results to results/ablation/<cell>_ep<N>/.

Usage:
    PYTHONPATH=. python scripts/make_epoch_eval_configs.py --cells Full3ep_s42
    PYTHONPATH=. python scripts/run_experiment.py \
        --config config/epoch_eval/Full3ep_s42_ep2/experiment_config.yml
"""

import argparse
import re
import sys
from pathlib import Path

import torch
import yaml

from src.utils.path_utils import resolve_project_path

CELL_ROOT = "config/ablation_config"
OUT_ROOT = "config/epoch_eval"
MODEL_ROOT = "models/ablation"
CHECKPOINT = re.compile(r"ldpc_rl_agent_(\d{8}_\d{6})_epoch(\d+)\.pth$")

HEADER = """# GENERATED by scripts/make_epoch_eval_configs.py from {source}.
# Scores the epoch {epoch} checkpoint of {cell} on that cell's held-out split.
# Evaluation only: no dataset creation, no training, baselines disabled because
# their numbers do not depend on the checkpoint.
# Do not edit; change the generator and regenerate.
"""


def sub_once(text, pattern, replacement):
    """Substitute exactly one match, so a source that drifted is noticed."""
    new_text, count = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"expected one match for {pattern!r}, found {count}")
    return new_text


def strip_leading_comments(text):
    lines = text.splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "".join(lines)


def weights(path):
    """The state dict alone; the metadata block carries a name and a timestamp."""
    return torch.load(path, map_location="cpu", weights_only=False)["state_dict"]


def same_weights(left, right):
    a, b = weights(left), weights(right)
    return sorted(a) == sorted(b) and all(torch.equal(a[k], b[k]) for k in a)


def checkpoints(cell):
    """The cell's epoch checkpoints and its final model, or an explanation."""
    folder = resolve_project_path(f"{MODEL_ROOT}/{cell}")
    if not folder.is_dir():
        raise SystemExit(f"{cell}: {folder} does not exist; has the cell run?")
    found = {}
    final = None
    for path in sorted(folder.iterdir()):
        match = CHECKPOINT.search(path.name)
        if match:
            found[int(match.group(2))] = path
        elif re.fullmatch(r"ldpc_rl_agent_\d{8}_\d{6}\.pth", path.name):
            final = path
    if not found:
        raise SystemExit(
            f"{cell}: no epoch checkpoints in {folder}. They are written only when "
            "training.save_epoch_checkpoints was set before the run, and cannot be "
            "reconstructed afterwards.")
    if final is None:
        raise SystemExit(f"{cell}: no final model in {folder}")
    return found, final


def eval_yaml(text, header, cell, epoch, checkpoint):
    label = f"{cell}_ep{epoch}"
    text = strip_leading_comments(text)
    text = sub_once(text, r'^(experiment_name:\s*)"[^"]*"', rf'\1"Ablation_64x128_{label}"')
    # The dataset is read, never written: the split must be the cell's own.
    text = sub_once(text, r"^(run_dataset_creation:\s*)true", r"\g<1>false")
    text = sub_once(text, r"^(run_training:\s*)true", r"\g<1>false")
    text = sub_once(text, r"^(\s*enabled:\s*)false(\s*#\s*Set to true to load)",
                    r"\g<1>true\2")
    text = sub_once(text, r'^(\s*model_path:\s*)"[^"]*"', rf'\1"{checkpoint}"')
    # Baseline results depend on the environment and the split, not the network,
    # so the cell's own numbers stand; scoring them again only costs time.
    text = sub_once(text, r'^(\s*- name:\s*"greedy"\n\s*enabled:\s*)true', r"\g<1>false")
    text = sub_once(text, r'^(\s*- name:\s*"min_sum_expert"\n\s*enabled:\s*)true', r"\g<1>false")
    text = sub_once(text, r'^(\s*results_dir:\s*)"[^"]*"', rf'\1"results/ablation/{label}/"')
    # A directory of its own, so a stray save cannot touch the cell's checkpoints.
    text = sub_once(text, r'^(\s*models_dir:\s*)"[^"]*"', rf'\1"models/ablation/{label}/"')
    return header + "\n" + text


def check(folder, cell, epoch, checkpoint):
    """Re-read the written config and confirm it evaluates and nothing else."""
    cfg = yaml.safe_load((folder / "experiment_config.yml").read_text())
    assert cfg["experiment_name"] == f"Ablation_64x128_{cell}_ep{epoch}"
    assert cfg["run_dataset_creation"] is False
    assert cfg["run_training"] is False
    assert cfg["run_evaluation"] is True
    assert cfg["load_pretrained_model"]["enabled"] is True
    assert cfg["load_pretrained_model"]["model_path"] == checkpoint
    assert not [a for a in cfg["evaluation"]["baseline_agents"] if a["enabled"]]
    assert cfg["output_paths"]["results_dir"] == f"results/ablation/{cell}_ep{epoch}/"
    # The held-out split is derived from the dataset, its test_size and the seed,
    # so all three must stay exactly as the cell had them.
    source = yaml.safe_load(
        resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml").read_text())
    assert cfg["seed"] == source["seed"]
    assert cfg["dataset_creation"]["output_path"] == source["dataset_creation"]["output_path"]
    assert cfg["dataset_creation"]["test_size"] == source["dataset_creation"]["test_size"]
    assert cfg["environment"] == source["environment"]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--cells", nargs="+", required=True,
                        help="cell names under config/ablation_config/, e.g. Full3ep_s42")
    args = parser.parse_args()

    written = []
    for cell in args.cells:
        source = resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml")
        if not source.is_file():
            raise SystemExit(f"{cell}: {source} does not exist")
        base = source.read_text()
        found, final = checkpoints(cell)
        last = max(found)

        if not same_weights(found[last], final):
            raise SystemExit(
                f"{cell}: the epoch {last} checkpoint does not hold the same weights as "
                f"{final.name}. The cell's own evaluation therefore does not score the "
                "last epoch, and that epoch needs a config of its own.")

        for epoch in sorted(found):
            if epoch == last:
                continue  # Already scored: same weights as the model the cell evaluated.
            checkpoint = f"{MODEL_ROOT}/{cell}/{found[epoch].name}"
            folder = resolve_project_path(f"{OUT_ROOT}/{cell}_ep{epoch}")
            folder.mkdir(parents=True, exist_ok=True)
            header = HEADER.format(source=f"{CELL_ROOT}/{cell}", cell=cell, epoch=epoch)
            (folder / "experiment_config.yml").write_text(
                eval_yaml(base, header, cell, epoch, checkpoint))
            check(folder, cell, epoch, checkpoint)
            written.append(f"{cell}_ep{epoch}")

        print(f"{cell}: epoch {last} needs no config; its weights are {final.name}")

    print(f"\nWrote {len(written)} evaluation-only configs under {OUT_ROOT}/:")
    for label in written:
        print(f"  {label}")


if __name__ == "__main__":
    main()
