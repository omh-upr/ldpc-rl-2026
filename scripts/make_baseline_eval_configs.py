#!/usr/bin/env python3
"""
Write evaluation-only configs that score an added baseline on the ablation splits.

A baseline's result depends on the environment and the held-out words, not on any
network, so a baseline added after the campaign is scored on each seed's two
held-out splits without retraining anything: the curriculum split through the
seed's `Full` cell and the flat split through its `OnlyE` cell. Each config reads
its cell's dataset (never writes it), trains nothing, loads no model, and enables
only the new baseline.

Configs land under config/baseline_eval/<agent>_<split>_s<seed>/, outside
config/ablation_config/ so the orchestrator's folder discovery is unaffected, and
write to results/ablation/baseline_eval/<agent>_<split>_s<seed>/.

The Gallager-B thresholds are the ones selected on training words by
scripts/select_gallager_b_thresholds.py (docs/ablation/GALLAGER_B_SELECTION.md).

Usage:
    PYTHONPATH=. python scripts/make_baseline_eval_configs.py [--seeds 42 ...]
    PYTHONPATH=. python scripts/run_experiment.py \
        --config config/baseline_eval/gallager_b_curriculum_s42/experiment_config.yml
"""

import argparse
import re

import yaml

from src.utils.path_utils import resolve_project_path

CELL_ROOT = "config/ablation_config"
OUT_ROOT = "config/baseline_eval"
AGENT = "gallager_b"
# Selected on training words; see docs/ablation/GALLAGER_B_SELECTION.md.
PARAMETERS = {"max_iterations": 20, "thresholds": {3: 2, 5: 4}}
SPLITS = {"curriculum": "Full", "flat": "OnlyE"}

HEADER = """# GENERATED by scripts/make_baseline_eval_configs.py from {source}.
# Scores the {agent} baseline on the {split} held-out split of seed {seed}.
# Evaluation only: the dataset is read, nothing is trained, no model is loaded,
# and every other baseline is off because the cell already scored them.
# Do not edit; change the generator and regenerate.
"""


def sub_once(text, pattern, replacement):
    new_text, count = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"expected one match for {pattern!r}, found {count}")
    return new_text


def strip_leading_comments(text):
    lines = text.splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "".join(lines)


def eval_yaml(text, header, label):
    text = strip_leading_comments(text)
    text = sub_once(text, r'^(experiment_name:\s*)"[^"]*"', rf'\1"Ablation_64x128_{label}"')
    text = sub_once(text, r"^(run_dataset_creation:\s*)true", r"\g<1>false")
    text = sub_once(text, r"^(run_training:\s*)true", r"\g<1>false")
    text = sub_once(text, r'^(\s*- name:\s*"greedy"\n\s*enabled:\s*)true', r"\g<1>false")
    text = sub_once(text, r'^(\s*- name:\s*"min_sum_expert"\n\s*enabled:\s*)true', r"\g<1>false")
    thresholds = ", ".join(f"{d}: {b}" for d, b in PARAMETERS["thresholds"].items())
    entry = (f'    - name: "{AGENT}"\n'
             f"      enabled: true\n"
             f"      max_iterations: {PARAMETERS['max_iterations']}\n"
             f"      thresholds: {{{thresholds}}}  # selected on training words\n")
    text = sub_once(text, r'^([ \t]*- name:[ \t]*"min_sum_expert"\n[ \t]*enabled:[ \t]*false[ \t]*\n)',
                    lambda m: m.group(1) + entry)
    text = sub_once(text, r'^(\s*results_dir:\s*)"[^"]*"', rf'\1"results/ablation/baseline_eval/{label}/"')
    text = sub_once(text, r'^(\s*models_dir:\s*)"[^"]*"', rf'\1"models/ablation/baseline_eval/{label}/"')
    return header + "\n" + text


def check(folder, cell, label):
    cfg = yaml.safe_load((folder / "experiment_config.yml").read_text())
    source = yaml.safe_load(resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml").read_text())
    assert cfg["run_dataset_creation"] is False and cfg["run_training"] is False
    assert cfg["run_evaluation"] is True
    assert cfg["load_pretrained_model"]["enabled"] is False
    enabled = [a for a in cfg["evaluation"]["baseline_agents"] if a["enabled"]]
    assert [a["name"] for a in enabled] == [AGENT], enabled
    assert enabled[0]["thresholds"] == PARAMETERS["thresholds"]
    assert enabled[0]["max_iterations"] == PARAMETERS["max_iterations"]
    # The held-out split is derived from the dataset, its test_size and the seed.
    assert cfg["seed"] == source["seed"]
    assert cfg["dataset_creation"] == {**source["dataset_creation"]}
    assert cfg["environment"] == source["environment"]
    assert cfg["output_paths"]["results_dir"] == f"results/ablation/baseline_eval/{label}/"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--seeds", type=int, nargs="+", default=[42, 43, 44, 45, 46])
    args = parser.parse_args()
    written = []
    for seed in args.seeds:
        for split, condition in SPLITS.items():
            cell = f"{condition}_s{seed}"
            label = f"{AGENT}_{split}_s{seed}"
            source = resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml")
            folder = resolve_project_path(f"{OUT_ROOT}/{label}")
            folder.mkdir(parents=True, exist_ok=True)
            header = HEADER.format(source=f"{CELL_ROOT}/{cell}", agent=AGENT, split=split, seed=seed)
            (folder / "experiment_config.yml").write_text(eval_yaml(source.read_text(), header, label))
            check(folder, cell, label)
            written.append(label)
    print(f"Wrote {len(written)} evaluation-only configs under {OUT_ROOT}/:")
    for label in written:
        print(f"  {label}")


if __name__ == "__main__":
    main()
