#!/usr/bin/env python3
"""
Choose the Gallager-B thresholds on training words, and record the choice.

Gallager's optimal threshold b depends on the channel crossover probability and on
the iteration; these experiments have no channel, so b is a free setting per
variable degree. Picking it on the held-out words would tune the baseline on the
test set. This script picks it on the training split instead: it decodes a sample
of training words of the seed-42 curriculum dataset (the same seed and split the
base configuration was chosen on) for every threshold pair in the grid, and
selects the pair with the highest rate of exact recovery within the flip budget,
at the iteration limit of 20 that Min-Sum also uses. The 100-iteration column is
reported, not selected on.

It writes docs/ablation/GALLAGER_B_SELECTION.md and a JSON sidecar in full; do not
edit them.

Usage:
    PYTHONPATH=. python scripts/select_gallager_b_thresholds.py [--sample 20000]
"""

import argparse
import datetime as dt
import itertools
import json

import h5py
import numpy as np

from src.advanced.gallager_b import GallagerBDecoder, majority_thresholds
from src.utils.path_utils import resolve_project_path

DATASET = "data/ablation/s42/curriculum.h5"
H_PATH = "data/H_64x128_dmin14.npy"
OUTPUT = "docs/ablation/GALLAGER_B_SELECTION.md"
FLIP_BUDGET = 7
ITERATIONS = 20


def training_sample(path, size, seed):
    with h5py.File(path, "r") as h:
        phases = sorted((k for k in h if k.startswith("phase_")), key=lambda k: int(k.split("_")[1]))
        original = np.concatenate([h[f"{p}/original_codewords"][:] for p in phases])
        noisy = np.concatenate([h[f"{p}/noisy_codewords"][:] for p in phases])
        train = h["splits/train_indices"][:]
    pick = np.random.default_rng(seed).choice(train, size, replace=False)
    return original[pick].astype(np.int64), noisy[pick].astype(np.int64)


def score(decoder, original, noisy):
    ok = np.zeros(len(noisy), dtype=bool)
    iterations = np.zeros(len(noisy))
    for i in range(len(noisy)):
        x, converged, it = decoder.decode(noisy[i])
        ok[i] = converged and np.array_equal(x, original[i]) and (x != noisy[i]).sum() <= FLIP_BUDGET
        iterations[i] = it
    return ok, iterations


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--sample", type=int, default=20000)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    H = np.load(resolve_project_path(H_PATH)) % 2
    degrees = sorted(set(H.sum(axis=0).astype(int).tolist()))
    original, noisy = training_sample(resolve_project_path(DATASET), args.sample, args.seed)
    weight = (original != noisy).sum(axis=1)
    default = majority_thresholds(H.sum(axis=0))

    grid = list(itertools.product(*[range(1, d) for d in degrees]))
    rows = []
    for combo in grid:
        thresholds = dict(zip(degrees, combo))
        ok20, it20 = score(GallagerBDecoder(H, ITERATIONS, thresholds), original, noisy)
        ok100, _ = score(GallagerBDecoder(H, 100, thresholds), original, noisy)
        rows.append((thresholds, 100 * ok20.mean(), 100 * ok100.mean(), it20.mean(),
                     [100 * ok20[weight == w].mean() for w in range(1, 7)]))
        print(f"{thresholds}: {rows[-1][1]:.2f}% at {ITERATIONS} iterations", flush=True)
    best = max(rows, key=lambda r: r[1])

    def label(t):
        tags = []
        if t == default:
            tags.append("majority")
        if all(t[d] == d - 1 for d in degrees):
            tags.append("Gallager A")
        return f"{t}" + (f" ({', '.join(tags)})" if tags else "")

    L = ["# Gallager-B threshold selection\n",
         f"Generated by `scripts/select_gallager_b_thresholds.py` on {dt.date.today().isoformat()}. "
         "Do not edit; rerun the script.\n",
         f"Sample: {args.sample:,} words drawn (seed {args.seed}) from the **training** split of "
         f"`{DATASET}`; the held-out words play no part. A word counts as recovered when the "
         f"decoder converges to the transmitted codeword with at most {FLIP_BUDGET} bits "
         f"changed, which is what the environment scores as success. Variable degrees "
         f"{degrees}; for degree $d$, $b$ ranges over $1, \\dots, d-1$.\n",
         "| Thresholds $b$ by degree | Recovered, 20 it (%) | Recovered, 100 it (%) | "
         "Mean iterations (20) | Weight 1 to 6 (%) at 20 it |",
         "|---|--:|--:|--:|---|"]
    for t, s20, s100, it, byw in sorted(rows, key=lambda r: -r[1]):
        mark = " **selected**" if r_is(t, best[0]) else ""
        L.append(f"| {label(t)}{mark} | {s20:.2f} | {s100:.2f} | {it:.2f} | "
                 + " ".join(f"{x:.0f}" for x in byw) + " |")
    L.append("")
    L.append(f"Selected: $b$ = {best[0]} at {ITERATIONS} iterations, recovering "
             f"{best[1]:.2f}% of the sample. The evaluation configs written by "
             "`scripts/make_baseline_eval_configs.py` pass these thresholds to "
             "`GallagerBAgent`.\n")
    out = resolve_project_path(OUTPUT)
    out.write_text("\n".join(L))
    out.with_suffix(".json").write_text(json.dumps({
        "generated": dt.date.today().isoformat(), "dataset": DATASET, "sample": args.sample,
        "iterations": ITERATIONS, "selected": {str(k): v for k, v in best[0].items()},
        "rows": [{"thresholds": {str(k): v for k, v in t.items()}, "recovered_20": s20,
                  "recovered_100": s100, "mean_iterations_20": it, "by_weight_20": byw,
                  "majority": t == default,
                  "gallager_a": all(t[d] == d - 1 for d in degrees)}
                 for t, s20, s100, it, byw in rows]}, indent=1))
    print(f"selected {best[0]}; wrote {OUTPUT}")


def r_is(a, b):
    return dict(a) == dict(b)


if __name__ == "__main__":
    main()
