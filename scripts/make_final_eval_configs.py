#!/usr/bin/env python3
"""
Write evaluation-only configs that re-score a cell from its saved final weights.

A cell's own configuration trains before it evaluates, so on a checkout that
holds a cell's weights but not its result files, evaluating it would mean
training it again. This script writes, for each cell, a config that creates or
reuses the cell's dataset, skips training, loads the cell's final weights and
evaluates them with the cell's baselines, reproducing the cell's evaluation
files. The repository publishes the final weights of the paper's final policy,
`NoC_NoE3ep` on five seeds, which is the default.

Each config sits under config/final_eval/<cell>/, a folder named after the cell,
so the scripts that read a cell by name accept the tree in place of
config/ablation_config/ (`--config-root config/final_eval`). Results go to
results/ablation/final_eval/<cell>/, beside the cell's own; the model folder is
the cell's, where the weights are, and an evaluation-only run saves no model.

Usage:
    PYTHONPATH=. python scripts/make_final_eval_configs.py [--cells NoC_NoE3ep_s42 ...]
    PYTHONPATH=. python scripts/run_experiment.py \
        --config config/final_eval/NoC_NoE3ep_s42/experiment_config.yml
"""

import argparse
import re

import yaml

from scripts.make_epoch_eval_configs import strip_leading_comments, sub_once
from src.utils.path_utils import resolve_project_path

CELL_ROOT = "config/ablation_config"
OUT_ROOT = "config/final_eval"
MODEL_ROOT = "models/ablation"
DEFAULT_CELLS = [f"NoC_NoE3ep_s{s}" for s in (42, 43, 44, 45, 46)]
FINAL = re.compile(r"ldpc_rl_agent_\d{8}_\d{6}\.pth")

HEADER = """# GENERATED by scripts/make_final_eval_configs.py from {source}.
# Re-scores {cell} from its final weights on that cell's held-out split, with the
# cell's baselines. Evaluation only: the dataset is created or reused, nothing is
# trained and no model is saved.
# Do not edit; change the generator and regenerate.
"""


def final_model(cell):
    folder = resolve_project_path(f"{MODEL_ROOT}/{cell}")
    found = sorted(p.name for p in folder.iterdir() if FINAL.fullmatch(p.name)) \
        if folder.is_dir() else []
    if len(found) != 1:
        raise SystemExit(f"{cell}: expected one final model in {folder}, found {len(found)}")
    return f"{MODEL_ROOT}/{cell}/{found[0]}"


def eval_yaml(text, header, cell, model):
    text = strip_leading_comments(text)
    text = sub_once(text, r'^(experiment_name:\s*)"[^"]*"', rf'\1"Ablation_64x128_{cell}_final"')
    # Dataset creation stays on: it builds the cell's dataset on a fresh checkout
    # and reuses the file, after checking it matches, where it exists.
    text = sub_once(text, r"^(run_training:\s*)true", r"\g<1>false")
    text = sub_once(text, r"^(\s*enabled:\s*)false(\s*#\s*Set to true to load)",
                    r"\g<1>true\2")
    text = sub_once(text, r'^(\s*model_path:\s*)"[^"]*"', rf'\1"{model}"')
    text = sub_once(text, r'^(\s*results_dir:\s*)"[^"]*"',
                    rf'\1"results/ablation/final_eval/{cell}/"')
    return header + "\n" + text


def check(folder, cell, model):
    """Re-read the written config: it must evaluate the cell's weights on the
    cell's split with the cell's baselines, and train nothing."""
    cfg = yaml.safe_load((folder / "experiment_config.yml").read_text())
    source = yaml.safe_load(
        resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml").read_text())
    assert cfg["experiment_name"] == f"Ablation_64x128_{cell}_final"
    assert cfg["run_dataset_creation"] is True
    assert cfg["run_training"] is False
    assert cfg["run_evaluation"] is True
    assert cfg["load_pretrained_model"]["enabled"] is True
    assert cfg["load_pretrained_model"]["model_path"] == model
    assert cfg["load_pretrained_model"].get("overwrite", False) is False
    assert cfg["output_paths"]["results_dir"] == f"results/ablation/final_eval/{cell}/"
    assert cfg["output_paths"]["models_dir"] == source["output_paths"]["models_dir"]
    # The held-out split derives from the dataset, its test_size and the seed.
    for key in ("seed", "code_id", "environment", "dataset_creation", "evaluation"):
        assert cfg[key] == source[key], key


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--cells", nargs="+", default=DEFAULT_CELLS,
                        help="cell names under config/ablation_config/ (default: the "
                             "final policy's five cells)")
    args = parser.parse_args()

    for cell in args.cells:
        source = resolve_project_path(f"{CELL_ROOT}/{cell}/experiment_config.yml")
        if not source.is_file():
            raise SystemExit(f"{cell}: {source} does not exist")
        model = final_model(cell)
        folder = resolve_project_path(f"{OUT_ROOT}/{cell}")
        folder.mkdir(parents=True, exist_ok=True)
        header = HEADER.format(source=f"{CELL_ROOT}/{cell}", cell=cell)
        (folder / "experiment_config.yml").write_text(
            eval_yaml(source.read_text(), header, cell, model))
        check(folder, cell, model)
        print(f"{OUT_ROOT}/{cell}: evaluates {model}")


if __name__ == "__main__":
    main()
