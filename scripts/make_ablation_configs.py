#!/usr/bin/env python3
"""
Write the ablation cells described in docs/ablation/PROTOCOL.md.

One folder per (condition, seed) under config/ablation_config/, each holding
the four files the orchestrator requires. Everything derives from the base
folder and the flat mixture, so a change is made there and the folders are
regenerated, never edited by hand. A cell whose results folder already holds
files is refused, so a finished cell cannot be silently redefined.

The four one-epoch conditions are the frozen 2x2. Full3ep is the training
budget study: the Full condition again, on the same per-seed datasets and
expert replays, for three epochs on a halving epsilon ladder. Full3epFloor is
its attribution arm, identical but holding epochs 2 and 3 at the epsilon floor,
so the extra passes are separated from the reopened exploration. OnlyC3ep is
Full3ep without expert seeding, paired with it within each seed on the same
curriculum dataset, so it says whether seeding is a head start that further
passes erase or an advantage that lasts. NoC_NoE3ep is the same ladder with
neither mechanism, on the flat dataset, so paired with OnlyC3ep it isolates the
curriculum at three epochs. OnlyE3ep is the ladder with seeding on the flat
dataset, completing the 2x2 at three epochs: paired with NoC_NoE3ep it says
whether seeding is erased by further passes without the curriculum too.
Pass --conditions and --seeds to write only the new
cells, leaving the finished ones alone.

Usage:
    PYTHONPATH=. python scripts/make_ablation_configs.py [--force]
                                                         [--conditions Full3ep ...]
                                                         [--seeds 42 ...]
"""

import argparse
import copy
import json
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

from src.utils.path_utils import resolve_project_path

BASE = "config/experiments_config/64x128_Full_Uniform_NoReflip"
FLAT_SOURCE = "config/experiments_config/64x128_NoC_NoE/main_dataset_config.json"
OUT_ROOT = "config/ablation_config"
DATA_ROOT = "data/ablation"
SEEDS = [42, 43, 44, 45, 46]
EXPERT_SEED_OFFSET = 100

# Opening epsilon of a one-epoch cell, and of every first epoch: epoch 1 then
# repeats the one-epoch cells exactly, which is the determinism check.
EPSILON_START = 0.5
EPSILON_MIN = 0.01
PHASES = 6

# condition -> (curriculum, expert seeding, epochs, epsilon opening per epoch).
# Full3ep halves the opening each pass. Full3epFloor holds epochs 2 and 3 at the
# floor instead, which separates the extra passes from the re-exploration: the
# two conditions differ in nothing else, so a gain that survives here is bought
# by the passes and a gain that disappears was bought by reopening epsilon.
# OnlyC3ep runs the Full3ep ladder without seeding; its epoch 1 repeats OnlyC.
# NoC_NoE3ep runs it with neither mechanism; its epoch 1 repeats NoC_NoE.
# OnlyE3ep runs it with seeding alone; its epoch 1 repeats OnlyE.
CONDITIONS = {
    "NoC_NoE": (False, False, 1, None),
    "OnlyC": (True, False, 1, None),
    "OnlyE": (False, True, 1, None),
    "Full": (True, True, 1, None),
    "Full3ep": (True, True, 3, [EPSILON_START, 0.25, 0.125]),
    "Full3epFloor": (True, True, 3, [EPSILON_START, EPSILON_MIN, EPSILON_MIN]),
    "OnlyC3ep": (True, False, 3, [EPSILON_START, 0.25, 0.125]),
    "NoC_NoE3ep": (False, False, 3, [EPSILON_START, 0.25, 0.125]),
    "OnlyE3ep": (False, True, 3, [EPSILON_START, 0.25, 0.125]),
}

HEADER = """# GENERATED by scripts/make_ablation_configs.py from {base}.
# Cell {cell}: curriculum={curriculum}, expert seeding={expert}, epochs={epochs}, seed={seed}.
# Do not edit; change the base or the generator and regenerate.
# Design: docs/ablation/PROTOCOL.md
"""


def sub_once(text, pattern, replacement):
    """Substitute exactly one match, so a base file that drifted is noticed."""
    new_text, count = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"expected one match for {pattern!r}, found {count}")
    return new_text


def strip_leading_comments(text):
    lines = text.splitlines(keepends=True)
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "".join(lines)


def marginal(config):
    """Weight of each error source over the whole dataset."""
    total = sum(p["num_samples"] for p in config["curriculum"])
    acc = Counter()
    for phase in config["curriculum"]:
        for model in phase["error_models"]:
            key = (model["type"], json.dumps(model["params"], sort_keys=True))
            acc[key] += model["weight"] * phase["num_samples"] / total
    return acc


def main_dataset_config(base, flat_models, curriculum, seed):
    cfg = copy.deepcopy(base)
    cfg["seed"] = seed
    if not curriculum:
        cfg["dataset_name"] = "Robust_LDPC_Flat_Dataset_v1"
        for index, phase in enumerate(cfg["curriculum"], 1):
            phase["phase_name"] = f"Flat_{index}"
            phase["error_models"] = copy.deepcopy(flat_models)
    return cfg


def epsilon_ladder(ladder):
    """The per-epoch epsilon_start rows, one opening value per epoch.

    Depth selects the reading, so every epoch needs a full row of phase values:
    a flat list of one entry per epoch would be read as that many phases instead.
    """
    cells = [f"{value:g}" for value in ladder]
    width = max(len(cell) for cell in cells)
    indent = " " * len("  epsilon_start: [")
    lines = []
    for index, cell in enumerate(cells):
        row = "[" + ", ".join([cell.ljust(width)] * PHASES) + "]"
        opening = "  epsilon_start: [" if index == 0 else indent
        closing = "]" if index == len(ladder) - 1 else ","
        lines.append(f"{opening}{row}{closing}   # epoch {index + 1}")
    return "\n".join(lines)


def ladder_comment(ladder):
    """Say what this particular ladder does, since the two differ in intent."""
    if all(value == EPSILON_MIN for value in ladder[1:]):
        return ("  # Epoch 1 anneals as usual; every later epoch opens at the floor and\n"
                "  # therefore holds it throughout, so the extra passes add no exploration.\n"
                "  # A start equal to the floor is how an epoch holds it from its first\n"
                "  # episode: the annealing span has nowhere to fall.\n")
    return ("  # Each epoch restarts the curriculum at phase 1 and reopens epsilon at\n"
            "  # its own value, so every pass explores less and refines more.\n")


def multi_epoch(text, epochs, ladder):
    """Turn the one-epoch base into an `epochs`-pass run on the given ladder."""
    if len(ladder) != epochs:
        raise ValueError(f"ladder has {len(ladder)} openings for {epochs} epochs")
    text = sub_once(
        text, r"^(\s*num_epochs:\s*)1$",
        lambda m: f"{m.group(1)}{epochs}\n"
                  "  save_epoch_checkpoints: true  "
                  "# One snapshot per epoch, so each pass can be scored")
    return sub_once(
        text,
        r"^  # One value, broadcast to every phase: no taper across the curriculum\.\n"
        r"  epsilon_start: 0\.5   # Every phase opens here\n"
        r"  epsilon_min: 0\.01    # Every phase anneals to here, then holds it$",
        lambda m: "  # One row per epoch, uniform across the six phases within each row.\n"
                  + ladder_comment(ladder)
                  + epsilon_ladder(ladder) + "\n"
                  f"  epsilon_min: {EPSILON_MIN}    "
                  "# Every phase of every epoch anneals to here, then holds it")


def experiment_yaml(text, header, cell, seed, curriculum, expert, epochs, ladder, data_dir):
    dataset = f"{data_dir}/{'curriculum' if curriculum else 'flat'}.h5"
    text = strip_leading_comments(text)
    if epochs > 1:
        text = multi_epoch(text, epochs, ladder)
    text = sub_once(text, r'^(experiment_name:\s*)"[^"]*"', rf'\1"Ablation_64x128_{cell}"')
    text = sub_once(text, r"^(seed:\s*)\d+", rf"\g<1>{seed}")
    text = sub_once(text, r'^(\s*config_path:\s*)"[^"]*"',
                    rf'\1"{OUT_ROOT}/{cell}/main_dataset_config.json"')
    text = sub_once(text, r'^(\s*output_path:\s*)"[^"]*"', rf'\1"{dataset}"')
    text = sub_once(text, r"^(\s*force_recreate:\s*false)\s*#.*$",
                    r"\1 # Reuse the per-seed dataset; a file that does not match is refused")
    text = sub_once(text, r"^(\s*use_pregenerated_file:\s*)\w+", rf"\g<1>{str(expert).lower()}")
    text = sub_once(text, r'^(\s*pregenerated_file:\s*)"[^"]*"',
                    rf'\1"{data_dir}/omniscient_500000.pkl"')
    text = sub_once(text, r'^(\s*results_dir:\s*)"[^"]*"', rf'\1"results/ablation/{cell}/"')
    text = sub_once(text, r'^(\s*models_dir:\s*)"[^"]*"', rf'\1"models/ablation/{cell}/"')
    return header + "\n" + text


def expert_experience_yaml(text, header, seed, data_dir):
    text = strip_leading_comments(text)
    text = sub_once(text, r"^(seed:\s*)\d+", rf"\g<1>{seed}")
    text = sub_once(text, r"^(dataset:\s*)'[^']*'", rf"\1'{data_dir}/expert.h5'")
    text = sub_once(text, r"^(output_file:\s*)'[^']*'", rf"\1'{data_dir}/omniscient_500000.pkl'")
    return header + "\n" + text


def check_cell(folder, cell, seed, curriculum, expert, epochs, ladder, data_dir, curriculum_marginal):
    """Re-read the written files and confirm they say what the protocol says."""
    exp = yaml.safe_load((folder / "experiment_config.yml").read_text())
    assert exp["experiment_name"] == f"Ablation_64x128_{cell}"
    assert exp["seed"] == seed
    assert exp["training"]["num_epochs"] == epochs
    assert exp["training"]["epsilon_decay"] == "auto_episodes"
    if epochs == 1:
        assert exp["training"]["epsilon_start"] == EPSILON_START
        assert "save_epoch_checkpoints" not in exp["training"]
    else:
        # Every pass needs the weights kept, or the run yields one held-out
        # number and the epochs cannot be told apart.
        assert exp["training"]["save_epoch_checkpoints"] is True
        written_ladder = exp["training"]["epsilon_start"]
        assert len(written_ladder) == epochs, "one row per epoch, not one value per phase"
        for row, opening in zip(written_ladder, ladder):
            assert row == [opening] * PHASES
        # Epoch 1 must repeat the one-epoch cells, which is the determinism check.
        assert written_ladder[0][0] == EPSILON_START
        # A start below the floor is refused by the schedule; equal is what holds it.
        assert all(opening >= EPSILON_MIN for opening in ladder)
    assert exp["training"]["epsilon_min"] == EPSILON_MIN
    assert exp["environment"]["forbid_immediate_reflip"] is True
    assert exp["dataset_creation"]["config_path"] == f"{OUT_ROOT}/{cell}/main_dataset_config.json"
    assert exp["dataset_creation"]["output_path"] == f"{data_dir}/{'curriculum' if curriculum else 'flat'}.h5"
    assert exp["dataset_creation"]["force_recreate"] is False
    assert exp["expert_experience"]["use_pregenerated_file"] is expert
    assert exp["expert_experience"]["pregenerated_file"] == f"{data_dir}/omniscient_500000.pkl"
    assert exp["output_paths"]["results_dir"] == f"results/ablation/{cell}/"
    assert exp["output_paths"]["models_dir"] == f"models/ablation/{cell}/"
    assert {a["name"] for a in exp["evaluation"]["baseline_agents"] if a["enabled"]} == {"greedy", "min_sum_expert"}

    main = json.loads((folder / "main_dataset_config.json").read_text())
    assert main["seed"] == seed
    assert len(main["curriculum"]) == 6
    got = marginal(main)
    drift = max(abs(got[k] - curriculum_marginal[k]) for k in set(got) | set(curriculum_marginal))
    assert drift < 1e-9, f"mixture drifted from the curriculum marginal by {drift}"
    if not curriculum:
        first = main["curriculum"][0]["error_models"]
        assert all(p["error_models"] == first for p in main["curriculum"])

    ex_ds = json.loads((folder / "expert_dataset_config.json").read_text())
    assert ex_ds["seed"] == seed + EXPERT_SEED_OFFSET

    ex = yaml.safe_load((folder / "expert_experience_config.yml").read_text())
    assert ex["seed"] == seed
    assert ex["dataset"] == f"{data_dir}/expert.h5"
    assert ex["output_file"] == f"{data_dir}/omniscient_500000.pkl"
    assert ex["code_id"] == exp["code_id"] == "64x128"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--force", action="store_true",
                        help="rewrite a cell even if its results folder holds files")
    parser.add_argument("--conditions", nargs="+", choices=list(CONDITIONS),
                        default=list(CONDITIONS),
                        help="write only these conditions, leaving finished cells alone")
    parser.add_argument("--seeds", nargs="+", type=int, choices=SEEDS, default=SEEDS,
                        help="write only these seeds, for an arm that runs on fewer")
    args = parser.parse_args()

    base = resolve_project_path(BASE)
    base_main = json.loads((base / "main_dataset_config.json").read_text())
    base_expert_ds = json.loads((base / "expert_dataset_config.json").read_text())
    base_experiment = (base / "experiment_config.yml").read_text()
    base_experience = (base / "expert_experience_config.yml").read_text()
    flat_source = json.loads(resolve_project_path(FLAT_SOURCE).read_text())
    flat_models = flat_source["curriculum"][0]["error_models"]
    curriculum_marginal = marginal(base_main)

    written = []
    for seed in args.seeds:
        data_dir = f"{DATA_ROOT}/s{seed}"
        for condition in args.conditions:
            curriculum, expert, epochs, ladder = CONDITIONS[condition]
            cell = f"{condition}_s{seed}"
            results = resolve_project_path(f"results/ablation/{cell}")
            if results.exists() and any(results.iterdir()) and not args.force:
                sys.exit(f"{cell}: {results} already holds results; pass --force to redefine it")

            folder = resolve_project_path(f"{OUT_ROOT}/{cell}")
            folder.mkdir(parents=True, exist_ok=True)
            header = HEADER.format(base=BASE, cell=cell, curriculum=curriculum,
                                   expert=expert, epochs=epochs, seed=seed)

            main_cfg = main_dataset_config(base_main, flat_models, curriculum, seed)
            (folder / "main_dataset_config.json").write_text(json.dumps(main_cfg, indent=2) + "\n")

            expert_ds = copy.deepcopy(base_expert_ds)
            expert_ds["seed"] = seed + EXPERT_SEED_OFFSET
            (folder / "expert_dataset_config.json").write_text(json.dumps(expert_ds, indent=2) + "\n")

            (folder / "expert_experience_config.yml").write_text(
                expert_experience_yaml(base_experience, header, seed, data_dir))
            (folder / "experiment_config.yml").write_text(
                experiment_yaml(base_experiment, header, cell, seed, curriculum, expert,
                                epochs, ladder, data_dir))

            check_cell(folder, cell, seed, curriculum, expert, epochs, ladder, data_dir,
                       curriculum_marginal)
            written.append(cell)

    print(f"Wrote {len(written)} cells under {OUT_ROOT}/:")
    for cell in written:
        print(f"  {cell}")


if __name__ == "__main__":
    main()
